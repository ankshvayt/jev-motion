GLYPHS = {k: [[c == "1" for c in row] for row in v.split()] for k, v in _G.items()}


def render(text, path, scale=4, fg=(255, 255, 255), bg=(0, 0, 0), pad=2):
    """Write text (uppercased; unknown chars become '-') as an RGB PNG with a solid background."""
    glyphs = [GLYPHS.get(ch, GLYPHS["-"]) for ch in text.upper()]
    cols = len(glyphs) * 6 - 1 if glyphs else 1
    w, h = (cols + 2 * pad) * scale, (7 + 2 * pad) * scale
    rows = []
    for y in range(h):
        gy = y // scale - pad
        row = bytearray([0])
        for x in range(w):
            gx = x // scale - pad
            on = False
            if 0 <= gy < 7 and 0 <= gx < cols:
                gi, off = divmod(gx, 6)
                on = off < 5 and glyphs[gi][gy][off]
            row += bytes(fg if on else bg)
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    return w, h
